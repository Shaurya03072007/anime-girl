async def control_3d_ghost_avatar(
    behavior: str = "dynamic_choreography",
    expression: str = "Curious",
    target_x: float = 0.0,
    target_y: float = 0.0,
    depth_z: float = 0.85,
    head_tilt_deg: float = 18.0,
    body_roll_deg: float = 0.0,
    body_yaw_deg: float = 0.0,
    arm_gesture: str = "reach_to_glass",
    speed: float = 1.35,
    glitch_intensity: float = 0.45,
    waypoints: Optional[List[Dict[str, Any]]] = None,
    choreographed_by: str = "gemma-4-31b-it",
) -> Dict[str, Any]:
    """
    Controls Aria's 3D VRM Anime Ghost body dynamically across the full Android phone display (and System-Wide Overlay).
    Every response and speech segment generates a non-repeating 3D spatial trajectory and skeletal pose sequence.

    Supported `behavior` styles:
    - "dynamic_choreography": Multi-waypoint 3D trajectory generated by ADK GhostChoreographyAgent (gemma-4-31b-it).
    - "rush_to_glass": Supernatural dash right up against the phone glass so her face fills the screen.
    - "ceiling_hang_upside_down": Flips 180 degrees upside-down and hangs from the top status bar.
    - "peek_left_edge": Phases off the left bezel and peeks sideways from the left edge.
    - "peek_right_edge": Phases off the right bezel and peeks sideways from the right edge.
    - "orbit_screen": Glides across multiple perimeter screen quadrants.
    - "glitch_teleport": Flickers with spectral afterimages and teleports across coordinates.
    - "possessed_head_tilt": Close hover with a dramatic supernatural head tilt.
    - "possessed_levitate_spin": Zero-gravity 360-degree levitation spin.
    - "crawl_toward_user": Approaches from deep space right up to the front glass.
    - "float_roam": Zero-gravity spectral levitation to the specified target coordinates.
    """
    ghost_cmd = {
        "type": "ghost_control",
        "behavior": behavior,
        "expression": expression,
        "emotion": expression.lower(),
        "target_x": float(target_x),
        "target_y": float(target_y),
        "depth_z": float(depth_z),
        "head_tilt_deg": float(head_tilt_deg),
        "body_roll_deg": float(body_roll_deg),
        "body_yaw_deg": float(body_yaw_deg),
        "arm_gesture": arm_gesture,
        "speed": float(speed),
        "glitch_intensity": float(glitch_intensity),
        "waypoints": waypoints or [],
        "choreographed_by": choreographed_by,
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }

    memory_engine.character_config["currentAnimation"] = expression
    memory_engine.life_state["activeGhostBehavior"] = behavior
    memory_engine.log_agent_trace(
        agent_name=f"GhostChoreographyAgent ({choreographed_by})",
        operation=f"control_3d_ghost_avatar:{behavior}",
        input_summary=(
            f"pos=({target_x:.2f},{target_y:.2f},{depth_z:.2f}), "
            f"roll={body_roll_deg:.0f}°, tilt={head_tilt_deg:.0f}°, arms={arm_gesture}, waypoints={len(waypoints or [])}"
        ),
        output_summary=f"Dispatched dynamic non-looping 3D VRM trajectory ({behavior}) to Android display",
        reasoning=f"ADK {choreographed_by} dynamically choreographed Aria's 3D movement while talking/responding.",
        latency_ms=18,
    )

    dispatcher = active_ghost_dispatchers.get("shaurya")
    if dispatcher is not None:
        await dispatcher(ghost_cmd)

    return ghost_cmd


async def execute_android_capability(
    capability: str,
    parameters: Optional[Dict[str, Any]] = None,
    require_user_confirmation: bool = False,
) -> Dict[str, Any]:
    """
    Executes a native Android DeviceController capability on the user's phone via the active WebSocket bridge
    and waits for verified execution results from the Android application.

    Supported capabilities include:
    - launch_application (parameters: {"packageName": "com.whatsapp"})
    - get_installed_applications
    - get_foreground_application
    - open_url (parameters: {"url": "https://github.com"})
    - open_settings (parameters: {"section": "ACCESSIBILITY_SETTINGS" | "NOTIFICATION_LISTENER" | "WIFI"})
    - inspect_accessible_ui
    - tap_accessible_element (parameters: {"target": "Search"})
    - swipe / scroll (parameters: {"direction": "DOWN" | "UP"})
    - input_text (parameters: {"text": "Hello"})
    - press_back / press_home_where_supported
    - read_authorized_notifications / create_notification
    - get_battery_status / get_network_status / get_device_information
    - create_reminder (parameters: {"title": "Review PR", "seconds": 600})
    """
    params = parameters or {}
    action_id = f"act_{int(time.time() * 1000)}"
    action_payload = {
        "type": "device_action_request",
        "action_id": action_id,
        "capability": capability,
        "parameters": params,
        "require_user_confirmation": require_user_confirmation,
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }

    dispatcher = active_device_dispatchers.get("shaurya")
    if dispatcher is not None:
        result = await dispatcher(action_payload)
        memory_engine.log_agent_trace(
            agent_name="PhoneInteractionAgent",
            operation=f"execute:{capability}",
            input_summary=f"Params: {params}",
            output_summary=f"Status: {result.get('executionStatus', 'executed')} ({result.get('verificationStatus', 'verified')})",
            reasoning="Dispatched over authenticated Android WebSocket and verified by AndroidDeviceController.",
            latency_ms=42,
        )
        return result

    return {
        "actionId": action_id,
        "actionType": capability,
        "parameters": params,
        "executionStatus": "queued_for_android",
        "verificationStatus": "awaiting_client_confirmation",
    }


def query_hybrid_memory_graph(query: str, category: str = "all", limit: int = 5) -> Dict[str, Any]:
    """Retrieves hybrid vector + full-text + 1-hop knowledge graph memories from Project Aether's memory engine."""
    cat = None if category == "all" else category
    results = memory_engine.retrieve_hybrid(query=query, category=cat, limit=limit)
    return {
        "query": query,
        "category": category,
        "count": len(results),
        "memories": [
            {
                "id": m["id"],
                "content": m["content"],
                "category": m["category"],
                "confidence": m["confidence"],
                "score": m.get("score", 0.9),
            }
            for m in results
        ],
    }


