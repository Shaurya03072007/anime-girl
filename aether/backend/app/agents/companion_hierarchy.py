def infer_ghost_command_from_text(text: str, emotion: str = "Happy") -> Dict[str, Any]:
    """
    Generates an immediate, smooth, camera-framed 3D keyframe sequence from user/companion text
    while the full ADK `gemma-4-31b-it` GhostChoreographyAgent computes or as an instant speech reaction.
    """
    lower = (text or "").lower()
    rng = random.Random(f"{text}_{time.time_ns()}")

    if any(k in lower for k in ("close", "stare", "glass", "face", "look at me", "daggara")):
        behavior = "rush_to_glass"
        tx, ty, tz = rng.uniform(-0.08, 0.08), rng.uniform(-0.08, 0.02), rng.uniform(0.68, 0.82)
        roll, yaw, tilt = rng.uniform(-5, 5), rng.uniform(-10, 10), rng.choice([-18.0, 18.0, 22.0])
        arm_gesture = "reach_to_glass"
    elif any(k in lower for k in ("upside", "ceiling", "hang", "top", "reverse")):
        behavior = "ceiling_hang_upside_down"
        tx, ty, tz = rng.uniform(-0.18, 0.18), rng.uniform(1.08, 1.18), rng.uniform(0.28, 0.45)
        roll, yaw, tilt = 180.0 + rng.uniform(-6, 6), rng.uniform(-12, 12), rng.uniform(-16, 16)
        arm_gesture = "zero_g_spread"
    elif any(k in lower for k in ("left", "hide")):
        behavior = "peek_left_edge"
        tx, ty, tz = rng.uniform(-0.38, -0.28), rng.uniform(-0.06, 0.08), rng.uniform(0.35, 0.55)
        roll, yaw, tilt = -14.0, -18.0, -16.0
        arm_gesture = "wave_greet"
    elif any(k in lower for k in ("right", "peek")):
        behavior = "peek_right_edge"
        tx, ty, tz = rng.uniform(0.28, 0.38), rng.uniform(-0.06, 0.08), rng.uniform(0.35, 0.55)
        roll, yaw, tilt = 14.0, 18.0, 16.0
        arm_gesture = "wave_greet"
    elif any(k in lower for k in ("teleport", "glitch", "ghost", "possess", "haunt", "bhoot")):
        behavior = "glitch_teleport"
        tx, ty, tz = rng.uniform(-0.32, 0.32), rng.uniform(-0.10, 0.14), rng.uniform(0.22, 0.68)
        roll, yaw, tilt = rng.uniform(-12, 12), rng.uniform(-20, 20), rng.choice([-22.0, 22.0])
        arm_gesture = "possessed_claw"
    elif any(k in lower for k in ("spin", "dance", "twirl", "levitate")):
        behavior = "possessed_levitate_spin"
        tx, ty, tz = rng.uniform(-0.20, 0.20), rng.uniform(0.02, 0.14), rng.uniform(0.25, 0.55)
        roll, yaw, tilt = rng.uniform(-8, 8), rng.choice([-35.0, 35.0]), rng.uniform(-15, 15)
        arm_gesture = "excited_up"
    elif any(k in lower for k in ("orbit", "fly", "circle", "around")):
        behavior = "orbit_screen"
        tx, ty, tz = rng.uniform(-0.30, 0.30), rng.uniform(-0.08, 0.12), rng.uniform(0.20, 0.58)
        roll, yaw, tilt = rng.uniform(-10, 10), rng.uniform(-18, 18), rng.uniform(-14, 14)
        arm_gesture = "zero_g_spread"
    elif any(k in lower for k in ("crawl", "approach", "come here", "raa")):
        behavior = "crawl_toward_user"
        tx, ty, tz = rng.uniform(-0.12, 0.12), rng.uniform(-0.08, 0.02), rng.uniform(0.58, 0.76)
        roll, yaw, tilt = rng.uniform(-6, 6), rng.uniform(-12, 12), rng.choice([-16.0, 16.0])
        arm_gesture = "reach_to_glass"
    elif "?" in text or emotion in ("Curious", "Confused", "Thinking"):
        behavior = "possessed_head_tilt"
        tx, ty, tz = rng.uniform(-0.18, 0.18), rng.uniform(-0.05, 0.06), rng.uniform(0.38, 0.58)
        roll, yaw, tilt = rng.uniform(-6, 6), rng.uniform(-14, 14), rng.choice([-20.0, 20.0, -24.0, 24.0])
        arm_gesture = "curious_chin"
    else:
        behavior = "dynamic_choreography"
        tx, ty, tz = rng.uniform(-0.24, 0.24), rng.uniform(-0.06, 0.08), rng.uniform(0.24, 0.56)
        roll, yaw, tilt = rng.uniform(-7, 7), rng.uniform(-16, 16), rng.uniform(-15, 15)
        arm_gesture = rng.choice(["wave_greet", "reach_to_glass", "curious_chin", "relaxed_float", "excited_up"])

    waypoints = [
        {
            "x": round(rng.uniform(-0.26, 0.26), 3),
            "y": round(ty if behavior == "ceiling_hang_upside_down" else rng.uniform(-0.06, 0.09), 3),
            "z": round(rng.uniform(0.20, 0.60), 3),
            "roll_deg": round(roll if behavior == "ceiling_hang_upside_down" else rng.uniform(-8, 8), 1),
            "yaw_deg": round(rng.uniform(-18, 18), 1),
            "head_tilt_deg": round(rng.uniform(-18, 18), 1),
            "arm_gesture": rng.choice(["wave_greet", "curious_chin", "relaxed_float", "reach_to_glass"]),
            "duration_sec": round(rng.uniform(1.3, 2.0), 2),
        },
        {
            "x": round(tx, 3),
            "y": round(ty, 3),
            "z": round(tz, 3),
            "roll_deg": round(roll, 1),
            "yaw_deg": round(yaw, 1),
            "head_tilt_deg": round(tilt, 1),
            "arm_gesture": arm_gesture,
            "duration_sec": round(rng.uniform(1.5, 2.3), 2),
        },
    ]

    return {
        "type": "ghost_control",
        "behavior": behavior,
        "expression": emotion,
        "emotion": emotion.lower(),
        "target_x": round(tx, 3),
        "target_y": round(ty, 3),
        "depth_z": round(tz, 3),
        "head_tilt_deg": round(tilt, 1),
        "body_roll_deg": round(roll, 1),
        "body_yaw_deg": round(yaw, 1),
        "arm_gesture": arm_gesture,
        "speed": 1.15 if behavior in ("rush_to_glass", "glitch_teleport", "orbit_screen") else 0.95,
        "glitch_intensity": 0.65 if behavior == "glitch_teleport" else 0.15,
        "waypoints": waypoints,
        "choreographed_by": settings.gemini_ghost_model,
    }


async def choreograph_ghost_with_adk_gemma(
    user_text: str,
    companion_speech: str,
    emotion: str = "Curious",
    is_speaking: bool = True,
) -> Dict[str, Any]:
    """
    Uses the Google ADK `GhostChoreographyAgent` with model `gemma-4-31b-it` (`settings.gemini_ghost_model`)
    to dynamically choreograph Aria's 3D VRM spatial path, body roll, head tilt, and arm gestures for
    every response — guarded by a non-blocking concurrency lock so API calls never pile up.
    """
    baseline = infer_ghost_command_from_text(f"{user_text} {companion_speech}", emotion=emotion)
    api_key = settings.gemini_api_key or settings.google_api_key
    if not api_key or _gemma_choreography_lock.locked():
        return await control_3d_ghost_avatar(**{k: v for k, v in baseline.items() if k not in ("type", "emotion")})

    async with _gemma_choreography_lock:
        prompt = (
            f"You are {ghost_choreography_agent.name}, an ADK 3D VRM Anime Companion Choreographer.\n"
            f"User said: {user_text[:200]}\n"
            f"Aria (3D anime companion) is speaking: {companion_speech[:280]}\n"
            f"Current emotion: {emotion} | is_speaking={is_speaking}\n\n"
            "Generate a natural, expressive, camera-framed 3D movement choreography.\n"
            "Safe camera-framed coordinate ranges:\n"
            "- target_x: -0.36 (left) to +0.36 (right)\n"
            "- target_y: -0.10 (lower) to +0.12 (upper), or +1.12 ONLY if behavior is ceiling_hang_upside_down\n"
            "- depth_z: 0.15 (full body view) to +0.78 (close-up portrait near glass)\n"
            "- head_tilt_deg: -24 to +24\n"
            "- body_roll_deg: -10 to +10 (or 180 if ceiling_hang_upside_down)\n"
            "- body_yaw_deg: -24 to +24\n"
            "- behavior: one of ['dynamic_choreography','rush_to_glass','ceiling_hang_upside_down','peek_left_edge','peek_right_edge','orbit_screen','glitch_teleport','possessed_head_tilt','possessed_levitate_spin','crawl_toward_user']\n"
            "- arm_gesture: one of ['reach_to_glass','wave_greet','zero_g_spread','curious_chin','possessed_claw','relaxed_float','excited_up']\n"
            "- waypoints: array of 2 sequential 3D keyframe objects {x, y, z, roll_deg, yaw_deg, head_tilt_deg, arm_gesture, duration_sec}.\n\n"
            "Return ONLY valid JSON matching those keys."
        )

        used_ghost_model = settings.gemini_ghost_model
        raw_json_str = ""

        try:
            client = genai.Client(
                api_key=api_key,
                http_options=types.HttpOptions(
                    timeout=12000,
                    retry_options=types.HttpRetryOptions(attempts=1),
                ),
            )
            try:
                resp = await asyncio.wait_for(
                    asyncio.to_thread(
                        client.models.generate_content,
                        model=settings.gemini_ghost_model,
                        contents=prompt,
                    ),
                    timeout=3.8,
                )
                raw_json_str = (resp.text or "").strip()
            except Exception:
                used_ghost_model = f"{settings.gemini_ghost_model}->{settings.gemini_ghost_fallback_model}"
                resp = await asyncio.wait_for(
                    asyncio.to_thread(
                        client.models.generate_content,
                        model=settings.gemini_ghost_fallback_model,
                        contents=prompt,
                    ),
                    timeout=3.5,
                )
                raw_json_str = (resp.text or "").strip()
        except Exception:
            pass

        parsed: Dict[str, Any] = {}
        if raw_json_str:
            match = re.search(r"\{.*\}", raw_json_str, re.DOTALL)
            if match:
                try:
                    parsed = json.loads(match.group(0))
                except Exception:
                    parsed = {}

        parsed_behavior = str(parsed.get("behavior") or "")
        if baseline["behavior"] != "dynamic_choreography":
            behavior = baseline["behavior"]
        else:
            behavior = parsed_behavior or baseline["behavior"]
        expression = str(parsed.get("expression") or emotion)
        is_upside_down = behavior == "ceiling_hang_upside_down"
        target_x = _clamp(parsed.get("target_x", baseline["target_x"]), -0.38, 0.38)
        target_y = (
            _clamp(parsed.get("target_y", 1.12), 1.02, 1.22)
            if is_upside_down
            else _clamp(parsed.get("target_y", baseline["target_y"]), -0.12, 0.14)
        )
        depth_z = _clamp(parsed.get("depth_z", baseline["depth_z"]), -0.25, 0.82)
        head_tilt_deg = _clamp(parsed.get("head_tilt_deg", baseline["head_tilt_deg"]), -28.0, 28.0)
        body_roll_deg = (
            180.0
            if is_upside_down
            else _clamp(parsed.get("body_roll_deg", baseline["body_roll_deg"]), -14.0, 14.0)
        )
        body_yaw_deg = _clamp(parsed.get("body_yaw_deg", baseline["body_yaw_deg"]), -28.0, 28.0)
        arm_gesture = str(parsed.get("arm_gesture") or baseline["arm_gesture"])
        speed = _clamp(parsed.get("speed", baseline["speed"]), 0.65, 1.35)
        glitch_intensity = _clamp(parsed.get("glitch_intensity", baseline["glitch_intensity"]), 0.0, 0.75)

        raw_wps = parsed.get("waypoints") if isinstance(parsed.get("waypoints"), list) and parsed.get("waypoints") else baseline["waypoints"]
        clamped_wps = []
        for wp in raw_wps[:3]:
            if not isinstance(wp, dict):
                continue
            clamped_wps.append(
                {
                    "x": round(_clamp(wp.get("x", target_x), -0.38, 0.38), 3),
                    "y": round(
                        _clamp(wp.get("y", 1.12), 1.02, 1.22)
                        if is_upside_down
                        else _clamp(wp.get("y", target_y), -0.12, 0.14),
                        3,
                    ),
                    "z": round(_clamp(wp.get("z", depth_z), -0.25, 0.82), 3),
                    "roll_deg": round(
                        180.0
                        if is_upside_down
                        else _clamp(wp.get("roll_deg", body_roll_deg), -14.0, 14.0),
                        1,
                    ),
                    "yaw_deg": round(_clamp(wp.get("yaw_deg", body_yaw_deg), -28.0, 28.0), 1),
                    "head_tilt_deg": round(_clamp(wp.get("head_tilt_deg", head_tilt_deg), -28.0, 28.0), 1),
                    "arm_gesture": str(wp.get("arm_gesture") or arm_gesture),
                    "duration_sec": round(_clamp(wp.get("duration_sec", 1.6), 1.1, 2.6), 2),
                }
            )

        return await control_3d_ghost_avatar(
            behavior=behavior,
            expression=expression,
            target_x=round(target_x, 3),
            target_y=round(target_y, 3),
            depth_z=round(depth_z, 3),
            head_tilt_deg=round(head_tilt_deg, 1),
            body_roll_deg=round(body_roll_deg, 1),
            body_yaw_deg=round(body_yaw_deg, 1),
            arm_gesture=arm_gesture,
            speed=round(speed, 2),
            glitch_intensity=round(glitch_intensity, 2),
            waypoints=clamped_wps or baseline["waypoints"],
            choreographed_by=used_ghost_model,
        )


async def run_live_companion_stream(
    user_id: str,
    session_id: str,
    live_request_queue: LiveRequestQueue,
    voice_name: str = "Zephyr",
):
    """
    Runs a real-time bidirectional Gemini Live session through Google ADK `Runner.run_live()`.
    Automatically falls back to `settings.gemini_live_fallback_model` if the primary model
    encounters a quota/availability error, logging the fallback explicitly.
    """
    runner = Runner(
        app_name=APP_NAME,
        agent=root_companion_agent,
        session_service=session_service,
    )

    run_config = RunConfig(
        streaming_mode=StreamingMode.BIDI,
        response_modalities=[types.Modality.AUDIO],
        speech_config=types.SpeechConfig(
            voice_config=types.VoiceConfig(
                prebuilt_voice_config=types.PrebuiltVoiceConfig(voice_name=voice_name)
            )
        ),
        output_audio_transcription=types.AudioTranscriptionConfig(),
        input_audio_transcription=types.AudioTranscriptionConfig(),
    )

    try:
        async for event in runner.run_live(
            user_id=user_id,
            session_id=session_id,
            live_request_queue=live_request_queue,
            run_config=run_config,
        ):
            yield event
    except Exception as primary_exc:
        print(
            f"[ADK Live] Primary live model '{root_companion_agent.model}' raised: {primary_exc}. "
            f"Switching to configured fallback '{settings.gemini_live_fallback_model}'."
        )
        root_companion_agent.model = settings.gemini_live_fallback_model
        root_companion_agent.generate_content_config = build_live_generate_content_config(
            settings.gemini_live_fallback_model,
            _initial_thinking_level,
        )
        async for event in runner.run_live(
            user_id=user_id,
            session_id=session_id,
            live_request_queue=live_request_queue,
            run_config=run_config,
        ):
            yield event
