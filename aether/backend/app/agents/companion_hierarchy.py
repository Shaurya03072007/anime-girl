LIVE_THINKING_LEVELS = {
    "LOW": types.ThinkingLevel.LOW,
    "MEDIUM": types.ThinkingLevel.MEDIUM,
    "HIGH": types.ThinkingLevel.HIGH,
}
AUTO_THINKING_START_LEVEL = "LOW"


def is_auto_thinking_mode() -> bool:
    return settings.gemini_live_thinking_level.strip().upper() in ("AUTO", "AUTOMATIC")


def validate_live_thinking_setting(value: str) -> str:
    """
    Validates GEMINI_LIVE_THINKING_LEVEL. The Live API for extended-thinking models only accepts
    LOW / MEDIUM / HIGH (MINIMAL and UNSPECIFIED are rejected with 1007). AUTO / AUTOMATIC is
    handled by the backend, which picks one of those three per turn.
    """
    normalized = (value or "AUTO").strip().upper()
    if normalized in ("AUTO", "AUTOMATIC"):
        return "AUTO"
    if normalized in LIVE_THINKING_LEVELS:
        return normalized
    return "AUTO"


def classify_thinking_level(text: str) -> str:
    """
    AUTO mode heuristic: picks the thinking level for the next live turn from what the user said.
    Quick chat -> LOW, multi-step or analytical requests -> MEDIUM, deep planning/debugging -> HIGH.
    """
    lower = (text or "").lower()
    words = len(lower.split())
    high_markers = (
        "step by step", "plan ", "planning", "architecture", "design a", "debug", "analyze",
        "analyse", "compare", "strategy", "prove", "explain why", "trade-off", "tradeoff",
    )
    medium_markers = (
        "how do", "how can", "why ", "explain", "summarize", "summarise", "remind", "schedule",
        "calculate", "what should", "help me", "difference", "open ", "find ",
    )
    if any(m in lower for m in high_markers) or words > 45:
        return "HIGH"
    if any(m in lower for m in medium_markers) or words > 18:
        return "MEDIUM"
    return "LOW"


def build_live_generate_content_config(model_name: str, thinking_level: str) -> Optional[types.GenerateContentConfig]:
    """Builds the thinking config for extended-thinking live models. `thinking_level` must be LOW/MEDIUM/HIGH."""
    if "thinking" not in model_name.lower():
        return None
    level = thinking_level.strip().upper()
    if level in ("AUTO", "AUTOMATIC"):
        level = AUTO_THINKING_START_LEVEL
    if level not in LIVE_THINKING_LEVELS:
        level = AUTO_THINKING_START_LEVEL
    return types.GenerateContentConfig(
        thinking_config=types.ThinkingConfig(thinking_level=LIVE_THINKING_LEVELS[level])
    )


