async def detect_and_execute_phone_intent(user_text: str) -> Optional[Dict[str, Any]]:
    """
    Deterministically detects phone control / status intents from user speech or text and
    executes them immediately via `execute_android_capability` on the connected Android phone.
    """
    lower = (user_text or "").lower()
    capability: Optional[str] = None
    params: Dict[str, Any] = {}

    if any(k in lower for k in ("battery", "charge", "charging", "power level")):
        capability = "get_battery_status"
    elif any(k in lower for k in ("wifi", "wi-fi", "network", "internet", "connection", "ip address")):
        capability = "get_network_status"
    elif any(k in lower for k in ("device info", "phone model", "android version", "which phone", "my phone spec")):
        capability = "get_device_information"
    elif any(k in lower for k in ("installed app", "what apps", "list apps", "apps on my phone")):
        capability = "get_installed_applications"
    elif any(k in lower for k in ("notification", "unread message", "any alerts")):
        capability = "read_authorized_notifications"
    elif any(k in lower for k in ("what is on my screen", "inspect screen", "read screen", "ui tree")):
        capability = "inspect_accessible_ui"
    elif any(k in lower for k in ("remind me", "set a reminder", "set a timer", "timer for", "alarm")):
        capability = "create_reminder"
        mins_match = re.search(r"(\d+)\s*(?:min|minute)", lower)
        secs = int(mins_match.group(1)) * 60 if mins_match else 300
        params = {"title": user_text[:60], "seconds": secs}
    elif any(k in lower for k in ("scroll down", "swipe down")):
        capability = "scroll"
        params = {"direction": "DOWN"}
    elif any(k in lower for k in ("scroll up", "swipe up")):
        capability = "scroll"
        params = {"direction": "UP"}
    elif "go back" in lower or "press back" in lower:
        capability = "press_back"
    elif "go home" in lower or "home screen" in lower or "press home" in lower:
        capability = "press_home_where_supported"
    elif any(k in lower for k in ("open ", "launch ", "start app ")):
        app_map = {
            "youtube": "com.google.android.youtube",
            "whatsapp": "com.whatsapp",
            "chrome": "com.android.chrome",
            "browser": "com.android.chrome",
            "github": "com.github.android",
            "gmail": "com.google.android.gm",
            "maps": "com.google.android.apps.maps",
            "camera": "com.sec.android.app.camera",
            "calculator": "com.google.android.calculator",
            "calendar": "com.google.android.calendar",
            "spotify": "com.spotify.music",
            "instagram": "com.instagram.android",
            "telegram": "org.telegram.messenger",
            "phone": "com.samsung.android.dialer",
        }
        if "settings" in lower:
            capability = "open_settings"
            if "accessibility" in lower:
                params = {"section": "ACCESSIBILITY_SETTINGS"}
            elif "notification" in lower:
                params = {"section": "NOTIFICATION_LISTENER"}
            else:
                params = {"section": "WIFI"}
        elif "http://" in lower or "https://" in lower or ".com" in lower:
            url_match = re.search(r"(https?://\S+|\b\w+\.com\S*)", lower)
            if url_match:
                url_val = url_match.group(1)
                if not url_val.startswith("http"):
                    url_val = f"https://{url_val}"
                capability = "open_url"
                params = {"url": url_val}
        else:
            for app_kw, pkg in app_map.items():
                if app_kw in lower:
                    capability = "launch_application"
                    params = {"packageName": pkg, "appName": app_kw}
                    break

    if not capability:
        return None

    res = await execute_android_capability(capability=capability, parameters=params)
    inner = res.get("result", res) if isinstance(res, dict) else {}
    if isinstance(inner, dict):
        if "batteryLevel" in inner:
            memory_engine.device_telemetry["batteryLevel"] = inner["batteryLevel"]
            memory_engine.device_telemetry["isCharging"] = inner.get("isCharging", False)
            memory_engine.save_snapshot()
        elif "networkType" in inner:
            memory_engine.device_telemetry["networkType"] = inner["networkType"]
            memory_engine.save_snapshot()
        elif "model" in inner:
            memory_engine.device_telemetry["deviceModel"] = f"{inner.get('manufacturer', '')} {inner.get('model', '')}".strip()
            memory_engine.device_telemetry["androidVersion"] = str(inner.get("androidRelease", "14"))
            memory_engine.save_snapshot()
    return {"capability": capability, "parameters": params, "result": res}


async def execute_turn_subagents(user_text: str, modality: str = "voice") -> Dict[str, Any]:
    """
    Co-executes ADK MemoryAgent + PhoneInteractionAgent on every user utterance (voice or text)
    so memories are always persisted, phone tools always execute, and context is always grounded.
    """
    memory_engine.append_conversation_turn(role="user", text=user_text, modality=modality, emotion="Listening")
    extracted_mem = memory_engine.auto_extract_and_store_memory(user_text, source_type=f"{modality}_conversation")
    phone_exec = await detect_and_execute_phone_intent(user_text)
    retrieved = memory_engine.retrieve_hybrid(user_text, limit=5)

    context_parts = []
    if extracted_mem:
        context_parts.append(f"Memory Saved: {extracted_mem['content']}")
    if phone_exec:
        context_parts.append(
            f"Phone Action Executed ({phone_exec['capability']}): {json.dumps(phone_exec['result'])[:320]}"
        )
    if retrieved:
        top_mems = "; ".join(m["content"] for m in retrieved[:4])
        context_parts.append(f"Relevant Memories: {top_mems}")

    tel = memory_engine.device_telemetry
    context_parts.append(
        f"Live Phone Status: Battery {tel.get('batteryLevel', 82)}% "
        f"({'Charging' if tel.get('isCharging') else 'Not Charging'}), "
        f"Network={tel.get('networkType', 'Wi-Fi')}, Device={tel.get('deviceModel', 'Android')}"
    )

    return {
        "extracted_memory": extracted_mem,
        "phone_execution": phone_exec,
        "retrieved_memories": retrieved,
        "context_summary": " | ".join(context_parts),
    }


